"""Build (and optionally execute) the analysis notebook.

The notebook is generated rather than hand-maintained so it cannot drift from
the source modules: every cell calls the same functions the scripts do. It
walks through loading records, inspecting a single example's signals,
comparing estimators, and reproducing the calibration and application results.

Usage::

    python scripts/build_notebook.py            # build and execute
    python scripts/build_notebook.py --no-exec  # build only
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import nbformat  # noqa: E402
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook  # noqa: E402

from src.config import NOTEBOOK_DIR, PROJECT_ROOT, ensure_output_dirs  # noqa: E402
from src.logging_utils import configure_logging  # noqa: E402

logger = logging.getLogger("build_notebook")

#: Filename of the generated notebook.
NOTEBOOK_NAME: str = "uncertainty_analysis.ipynb"

#: Seconds allowed per cell during execution.
_CELL_TIMEOUT: int = 300


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments.

    Returns:
        The parsed arguments.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--no-exec",
        action="store_true",
        help="Build the notebook without executing it.",
    )
    parser.add_argument("--output-dir", type=Path, default=NOTEBOOK_DIR)
    return parser.parse_args()


