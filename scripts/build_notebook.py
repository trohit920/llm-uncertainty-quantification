def main() -> int:
    """Build and optionally execute the notebook.

    Returns:
        Process exit code.
    """
    args = parse_args()
    configure_logging()
    ensure_output_dirs()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    notebook = new_notebook(cells=build_cells())
    notebook.metadata.kernelspec = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }

    path = args.output_dir / NOTEBOOK_NAME
    nbformat.write(notebook, path)
    logger.info("Wrote %s (%d cells)", path, len(notebook.cells))

    if args.no_exec:
        return 0

    from nbclient import NotebookClient

    logger.info("Executing notebook (this reads results/ and figures/)")
    client = NotebookClient(
        notebook,
        timeout=_CELL_TIMEOUT,
        kernel_name="python3",
        resources={"metadata": {"path": str(args.output_dir)}},
    )
    client.execute()
    nbformat.write(notebook, path)
    logger.info("Executed and saved %s", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
